// ---- main ----
function emit(r, fallback) {
  process.exitCode = r.ok ? EXIT.OK : EXIT.FAILED;
  const text = r.ok ? (r.out || fallback || '') : (r.err || r.out || fallback || 'failed');
  if (text) console.log(text);
}

export function main(argv = process.argv.slice(2)) {
  let parsed;
  try { parsed = parseGlobalFlags(argv); } catch (e) { console.error(`mobile-cli error: ${e.message}`); process.exit(e.exitCode || EXIT.USAGE); }
  const { args: all, statePath: flagPath } = parsed;
  const [cmd, ...args] = all;
  if (!cmd || cmd === '--help' || cmd === '-h') {
    console.log(HELP);
    process.exit(0);
  }
  if (cmd === 'version' || cmd === '--version') { console.log(readVersion()); process.exit(0); }

  const resolved = resolveStatePath(flagPath);
  STATE_PATH = resolved.path;
  STATE_PATH_EXPLICIT = resolved.explicit;
  const state = loadState();
  try {
    switch (cmd) {
      case 'set-device': {
        const id = args.find((a) => !a.startsWith('--'));
        const pi = args.indexOf('--platform');
        const platform = pi >= 0 ? args[pi + 1] : (args.find((a) => a.startsWith('--platform=')) || '').slice('--platform='.length) || undefined;
        if (platform && !['ios', 'android'].includes(platform)) throw new CliError('--platform must be ios or android', EXIT.USAGE);
        adoptDevice(state, resolveDevice(id, { platform }));
        console.log(`device=${state.device}${state.deviceName ? ` name=${state.deviceName}` : ''} platform=${state.platform} state=${STATE_PATH}`);
        return;
      }
      case 'boot': {
        adoptDevice(state, boot(args[0]));
        console.log(`booted ${state.deviceName || state.device} → device=${state.device} platform=${state.platform} state=${STATE_PATH}`);
        return;
      }
      case 'set-app': {
        reqDevice(state);
        if (!args[0]) throw new CliError('set-app <appId> required', EXIT.USAGE);
        state.appId = args[0];
        saveState(state);
        console.log(`appId=${state.appId}`);
        return;
      }
      case 'info': {
        console.log(JSON.stringify({
          state_file: STATE_PATH, device: state.device || null, deviceName: state.deviceName || null,
          platform: state.platform || null, appId: state.appId || null,
          refs: Object.keys(state.refs || {}).length, capturedAt: state.capturedAt || null,
          ref_ttl_ms: REF_TTL_MS, recording: readRec() ? readRec().outPath : null,
        }, null, 2));
        return;
      }
      case 'launch': return emit(launch(state), 'launched');
      case 'stop': return emit(stop(state), 'stopped');
      case 'relaunch-clean': return emit(relaunchClean(state), 'relaunched');
      case 'snapshot': {
        const { tree, count } = snapshot(state, { full: args.includes('--full') });
        console.log(tree);
        console.log(`\n(${count} refs captured; valid for ${REF_TTL_MS / 1000}s)`);
        return;
      }
      case 'click': return emit(tap(state, args[0]), `tapped ${args[0]}`);
      case 'tap-id': return emit(tapById(state, args[0]), `tapped id=${args[0]}`);
      case 'fill': return emit(fill(state, args[0], args.slice(1).join(' ')), `filled ${args[0]}`);
      case 'clear': return emit(clearField(state, args[0]), `cleared ${args[0]}`);
      case 'fill-id': return emit(fillById(state, args[0], args.slice(1).join(' ')), `filled id=${args[0]}`);
      case 'wait-text': {
        const t = args[1] ? Number(args[1]) : 10;
        if (!(t > 0)) throw new CliError('wait-text timeout must be a positive number of seconds', EXIT.USAGE);
        return emit(waitText(state, args[0], t));
      }
      case 'press': return emit(press(state, args[0]), `pressed ${args[0]}`);
      case 'screenshot': return emit(screenshot(state, args[0]), `saved ${args[0]}`);
      case 'logs': return emit(logs(state, args), '(no log lines)');
      case 'logs-clear': return emit(logsClear(state), 'cleared');
      case 'deep-link':
      case 'open-url': return emit(deepLink(state, args[0]), `opened ${args[0]}`);
      case 'running': return emit(running(state), '(nothing in foreground)');
      case 'record-start': return emit(recordStart(state, args[0]));
      case 'record-stop': return emit(recordStop());
      default:
        console.error(`Unknown command: ${cmd}. Run with --help.`);
        process.exit(EXIT.USAGE);
    }
  } catch (e) {
    console.error(`mobile-cli error: ${e.message}`);
    process.exit(e instanceof CliError ? e.exitCode : EXIT.FAILED);
  }
}

// Only run when executed directly (not when imported by tests). Compare real paths so a
// symlinked bin entry still counts as a direct invocation.
function isDirectInvocation() {
  const entry = process.argv[1];
  if (!entry) return false;
  try { return pathToFileURL(realpathSync(entry)).href === import.meta.url; }
  catch { return pathToFileURL(entry).href === import.meta.url; }
}
if (isDirectInvocation()) main();
