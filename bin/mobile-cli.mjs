#!/usr/bin/env node
// mobile-cli — Maestro-backed shim mimicking the playwright-cli command surface
// used by qualiow exploratory testing skills, adapted for iOS/Android.
//
// State file (first match wins):
//   --state <file>  |  $MOBILE_CLI_STATE  |  ~/.mobile-cli/current (pointer written by
//   set-device to a per-device file ~/.mobile-cli/<device>.json)  |  ~/.mobile-cli/state.json
//   { device, deviceName, platform, appId, refs: { e1: {id, text, x, y, bounds, class, kind} }, capturedAt }
//
// Commands:
//   set-device <id> [--platform ios|android]  persist target device: adb serial, sim UDID or sim name
//   set-app <bundleOrPackage>           persist app id
//   info                                show resolved state and the state file in use
//   boot <avd|sim-name|udid>            boot an Android AVD or iOS simulator, then set-device it
//   launch | stop | relaunch-clean      app lifecycle (relaunch-clean is android-only)
//   snapshot [--full]                   write refs, print ref'd tree (on-screen nodes only)
//   click <ref>                         tap element by ref (refs expire after MCLI_REF_TTL_MS, default 60s)
//   fill <ref> <text...>                tap then inputText (Maestro flow)
//   clear <ref>                         tap then erase the field's text (Maestro eraseText)
//   tap-id <testID>                     tap by testID directly (no snapshot needed)
//   fill-id <testID> <text...>          tapOn id + inputText in one Maestro flow
//   wait-text <substring> [timeout-sec] poll hierarchy for text to appear, default 10s
//   press <BACK|ENTER|HOME|TAB|ESCAPE>  (iOS: ENTER + HOME only)
//   screenshot <path>                   save PNG (no app required)
//   logs [--since <sec>] [--errors]     dump device logs (logcat / simctl log)
//   logs-clear                          clear device log buffer (android)
//   deep-link <url>                     open a deep link in the app
//   open-url <url>                      open a URL in the device browser (alias of deep-link)
//   running                             which activity / app is foreground
//   record-start <path.mp4>             begin video recording (mp4 container on both platforms)
//   record-stop                         stop video recording and pull the file
//   version                             print the mobile-cli version
//
// Exit codes: 0 ok · 1 command failed · 2 usage · 3 stale/unknown ref · 4 no device/app set
//
// Every Maestro flow is generated by buildFlow(), which serialises each scalar with
// JSON.stringify — a JSON string is a valid YAML double-quoted scalar, so quotes,
// newlines and backslashes in typed text can never inject extra flow steps.

import { execFileSync, spawn } from 'node:child_process';
import {
  existsSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, unlinkSync, writeFileSync,
} from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const MCLI_DIR = join(homedir(), '.mobile-cli');
const CURRENT_POINTER = join(MCLI_DIR, 'current');

export const EXIT = { OK: 0, FAILED: 1, USAGE: 2, REF: 3, NO_DEVICE: 4 };
export const REF_TTL_MS =
  Number(process.env.MCLI_REF_TTL_MS) > 0 ? Number(process.env.MCLI_REF_TTL_MS) : 60_000;

export class CliError extends Error {
  constructor(message, exitCode = EXIT.FAILED) {
    super(message);
    this.exitCode = exitCode;
  }
}

// Maestro prints an analytics banner on first run, corrupting parsed output
// (e.g. the hierarchy JSON). Opt out for every maestro child process.
process.env.MAESTRO_CLI_NO_ANALYTICS = process.env.MAESTRO_CLI_NO_ANALYTICS || '1';

// ---- state file ----
let STATE_PATH = join(MCLI_DIR, 'state.json');
let STATE_PATH_EXPLICIT = false; // --state flag or $MOBILE_CLI_STATE: never auto-switched per device

export function parseGlobalFlags(argv) {
  const args = [];
  let statePath = null;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--state') {
      statePath = argv[++i];
      if (!statePath) throw new CliError('--state needs a file path', EXIT.USAGE);
    } else if (a.startsWith('--state=')) {
      statePath = a.slice('--state='.length);
    } else {
      args.push(a);
    }
  }
  return { args, statePath };
}

export function resolveStatePath(flagPath, env = process.env) {
  if (flagPath) return { path: flagPath, explicit: true };
  if (env.MOBILE_CLI_STATE) return { path: env.MOBILE_CLI_STATE, explicit: true };
  if (existsSync(CURRENT_POINTER)) {
    const p = readFileSync(CURRENT_POINTER, 'utf8').trim();
    if (p) return { path: p, explicit: false };
  }
  return { path: join(MCLI_DIR, 'state.json'), explicit: false };
}

function loadStateFrom(path) {
  if (!existsSync(path)) return {};
  try { return JSON.parse(readFileSync(path, 'utf8')); } catch { return {}; }
}
function loadState() { return loadStateFrom(STATE_PATH); }
function saveState(s) {
  mkdirSync(dirname(STATE_PATH), { recursive: true });
  writeFileSync(STATE_PATH, JSON.stringify(s, null, 2));
}
function recPath() { return STATE_PATH.replace(/\.json$/, '') + '.rec.json'; }
export function sanitizeDeviceId(id) { return String(id).replace(/[^A-Za-z0-9._-]+/g, '_'); }

// ---- process helpers ----
function run(cmd, args, opts = {}) {
  return execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], ...opts });
}
function runOk(cmd, args, opts = {}) {
  try { return { ok: true, out: run(cmd, args, opts) }; }
  catch (e) { return { ok: false, out: e.stdout?.toString() || '', err: e.stderr?.toString() || e.message }; }
}
export function sleep(ms) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, Math.max(0, ms));
}

function reqDevice(s) {
  if (!s.device || !s.platform) throw new CliError('No device set. Run: mobile-cli set-device <serial|udid|sim-name> [--platform ios|android]', EXIT.NO_DEVICE);
  return s;
}
function reqApp(s) {
  reqDevice(s);
  if (!s.appId) throw new CliError('No app set. Run: mobile-cli set-app <bundleId|package>', EXIT.NO_DEVICE);
  return s;
}

// ---- device detection (pure parts are exported for tests) ----
export function parseAdbDevices(out) {
  return String(out || '')
    .split('\n')
    .slice(1)
    .map((l) => l.trim())
    .filter(Boolean)
    .map((l) => l.split(/\s+/))
    .filter(([serial, state]) => serial && state === 'device')
    .map(([serial]) => serial);
}

export function parseSimDevices(jsonText) {
  let j;
  try { j = typeof jsonText === 'string' ? JSON.parse(jsonText) : jsonText; } catch { return []; }
  const out = [];
  for (const [runtime, list] of Object.entries(j?.devices || {})) {
    for (const d of list || []) {
      out.push({ udid: d.udid, name: d.name, state: d.state, available: d.isAvailable !== false, runtime });
    }
  }
  return out;
}

// Resolve an id to { platform, device, deviceName } from what adb and simctl actually
// list. Never guesses from the shape or length of the string.
export function detectPlatform(id, { adbSerials = [], simDevices = [] } = {}) {
  if (!id) return null;
  if (adbSerials.includes(id)) return { platform: 'android', device: id };
  const lower = id.toLowerCase();
  const byUdid = simDevices.find((d) => (d.udid || '').toLowerCase() === lower);
  if (byUdid) return { platform: 'ios', device: byUdid.udid, deviceName: byUdid.name };
  const byName = simDevices.filter((d) => d.name === id && d.available);
  if (byName.length) {
    const pick = byName.find((d) => d.state === 'Booted') || byName[0];
    return { platform: 'ios', device: pick.udid, deviceName: pick.name };
  }
  return null;
}

function listAdbSerials() {
  const r = runOk('adb', ['devices']);
  return r.ok ? parseAdbDevices(r.out) : [];
}
function listSimDevices() {
  if (process.platform !== 'darwin') return [];
  const r = runOk('xcrun', ['simctl', 'list', 'devices', '-j']);
  return r.ok ? parseSimDevices(r.out) : [];
}

export function resolveDevice(id, { platform } = {}, probes = { adb: listAdbSerials, sim: listSimDevices }) {
  if (!id) throw new CliError('set-device <id> required', EXIT.USAGE);
  if (platform === 'android') return { platform: 'android', device: id };
  if (platform === 'ios') {
    const hit = detectPlatform(id, { simDevices: probes.sim() });
    return hit && hit.platform === 'ios' ? hit : { platform: 'ios', device: id };
  }
  const hit = detectPlatform(id, { adbSerials: probes.adb(), simDevices: probes.sim() });
  if (!hit) {
    throw new CliError(
      `Cannot tell whether '${id}' is an adb serial or an iOS simulator (not listed by \`adb devices\` or \`xcrun simctl list devices\`). Re-run: set-device ${id} --platform ios|android`,
      EXIT.USAGE,
    );
  }
  return hit;
}

// ---- Maestro flow builder: the ONLY producer of flow YAML ----
function yamlScalar(v) {
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (v === null || v === undefined) return '""';
  return JSON.stringify(String(v)); // JSON strings are valid YAML double-quoted scalars
}
function emitMap(obj, indent) {
  const pad = ' '.repeat(indent);
  const lines = [];
  for (const [k, v] of Object.entries(obj)) {
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      lines.push(`${pad}${k}:`);
      lines.push(...emitMap(v, indent + 2));
    } else {
      lines.push(`${pad}${k}: ${yamlScalar(v)}`);
    }
  }
  return lines;
}
export function buildFlow(appId, steps) {
  if (!appId) throw new CliError('buildFlow: appId required', EXIT.NO_DEVICE);
  const out = [`appId: ${yamlScalar(appId)}`, '---'];
  for (const step of steps) {
    if (typeof step === 'string') { out.push(`- ${yamlScalar(step)}`); continue; }
    const entries = Object.entries(step);
    if (entries.length !== 1) throw new CliError('buildFlow: each step must have exactly one command key');
    const [k, v] = entries[0];
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      out.push(`- ${k}:`);
      out.push(...emitMap(v, 4));
    } else {
      out.push(`- ${k}: ${yamlScalar(v)}`);
    }
  }
  return out.join('\n') + '\n';
}

// Maestro CLI has no `input` / `tap-by-id` one-shot commands, so we write a tiny flow
// to a private temp dir and run it via `maestro test`. Startup is ~3-5s, but avoids
// char-by-char IME re-renders that adb input text triggers on React Native TextInputs.
function runFlow(state, steps) {
  reqApp(state);
  const yaml = buildFlow(state.appId, steps);
  const dir = mkdtempSync(join(tmpdir(), 'mcli-')); // 0700
  const flowPath = join(dir, 'flow.yaml');
  try {
    writeFileSync(flowPath, yaml, { mode: 0o600 });
    return runOk('maestro', ['--device', state.device, 'test', flowPath]);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function maestro(state, args) {
  reqDevice(state);
  return runOk('maestro', ['--device', state.device, ...args]);
}

// ---- snapshot: parse maestro hierarchy → ref-numbered text tree ----
export function parseBounds(b) {
  // "[x1,y1][x2,y2]"
  const m = /^\[(-?\d+),(-?\d+)\]\[(-?\d+),(-?\d+)\]$/.exec(b || '');
  if (!m) return null;
  const [, x1, y1, x2, y2] = m.map(Number);
  return { x1, y1, x2, y2, cx: Math.round((x1 + x2) / 2), cy: Math.round((y1 + y2) / 2), w: x2 - x1, h: y2 - y1 };
}

// IDs to exclude as system chrome (status bar, navigation bar, notifications).
const SYSTEM_ID_PREFIXES = [
  'com.android.systemui:',
  'com.google.android.apps.nexuslauncher:',
  'android:id/statusBar',
  'android:id/navigationBarBackground',
];
function isSystemChrome(id) {
  return id && SYSTEM_ID_PREFIXES.some((p) => id.startsWith(p));
}

// Text patterns of dev-only chrome the app renders on top of every screen.
const DEV_CHROME_TEXT_PATTERNS = [
  /^Debug tools$/i, // floating bug button (debug-menu trigger)
];
function isDevChrome(text) {
  return text && DEV_CHROME_TEXT_PATTERNS.some((p) => p.test(text.trim()));
}

// ---- browser-target snapshot tuning ----
// When the "app under test" is a mobile browser driving a web app, the a11y tree is
// dominated by the browser's own shell plus wrapper containers around the rendered page.
// Gated on the app id being a known browser so native-app snapshots are unaffected.
const BROWSER_APP_IDS = [
  'com.apple.mobilesafari', // iOS Safari
  'com.android.chrome',     // Android Chrome
  'org.mozilla.firefox',    // Firefox (android)
  'com.microsoft.emmx',     // Edge (android)
];
export function isBrowserApp(appId) {
  return !!appId && BROWSER_APP_IDS.includes(appId);
}
// Pass-through wrappers: never emitted as a ref, but walked into.
const BROWSER_PASSTHROUGH_ID_PREFIXES = [
  'SafariWindow', 'TabDocument', 'WebView',
  'com.android.chrome:id/coordinator',
  'com.android.chrome:id/compositor_view_holder',
  'com.android.chrome:id/content',
];
function isBrowserPassthrough(id) {
  return id && BROWSER_PASSTHROUGH_ID_PREFIXES.some((p) => id.startsWith(p));
}
// Browser-own UI subtrees (address bar, tab bar, toolbar, keyboard, overlays): pruned.
const BROWSER_CHROME_ID_PREFIXES = [
  'CapsuleViewController', 'CapsuleNavigationBar', 'TabBarItemTitle', 'BackButton', 'ReloadButton',
  'MoreMenuButton', 'PageFormatMenuButton', 'AdditionalDimmingOverlay', 'Toolbar', 'inputView',
  'SystemInputAssistantView', 'UIKeyboardLayout', 'UIKeyboard', 'kb-autofill-key',
  'com.android.chrome:id/toolbar', 'com.android.chrome:id/url_bar', 'com.android.chrome:id/tab_switcher_button',
  'com.android.chrome:id/menu_button', 'com.android.chrome:id/control_container',
  'com.android.chrome:id/toolbar_container', 'com.android.chrome:id/bottom_container',
  'com.android.chrome:id/location_bar', 'com.android.chrome:id/omnibox',
  'com.android.chrome:id/message', 'com.android.chrome:id/infobar',
];
function isBrowserChrome(id) {
  return id && BROWSER_CHROME_ID_PREFIXES.some((p) => id.startsWith(p));
}

function isInteresting(attrs) {
  if (!attrs) return false;
  const cls = attrs.class || '';
  const id = attrs['resource-id'] || '';
  if (isSystemChrome(id)) return false;
  const text = attrs.text || attrs.accessibilityText || attrs.hintText || attrs.label || '';
  if (isDevChrome(text)) return false;
  const clickable = attrs.clickable === 'true' || attrs.clickable === true;
  if (id) return true;
  if (clickable && text) return true;
  if (/EditText|TextField|Button|CheckBox|Switch|TextView/i.test(cls) && (text || clickable)) return true;
  if (text && text.length > 0 && text.length < 200) return true; // visible text
  return false;
}

function summarizeClass(cls) {
  if (!cls) return '?';
  if (/EditText|TextField/i.test(cls)) return 'Input';
  if (/Button/i.test(cls)) return 'Button';
  if (/CheckBox/i.test(cls)) return 'Checkbox';
  if (/Switch/i.test(cls)) return 'Switch';
  if (/ImageView|Image\b/i.test(cls)) return 'Image';
  if (/TextView|StaticText|Label/i.test(cls)) return 'Text';
  if (/ViewGroup|Layout|Stack|Scroll/i.test(cls)) return 'Group';
  return cls.split('.').pop() || cls;
}

// `maestro hierarchy` is pure JSON since Maestro 2.6; older builds and stray log lines
// may precede it, so fall back to the first line that starts a JSON object.
export function parseHierarchy(stdout) {
  const text = String(stdout || '');
  try { return JSON.parse(text.trim()); } catch { /* fall through */ }
  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i++) {
    if (lines[i].trimStart().startsWith('{')) {
      try { return JSON.parse(lines.slice(i).join('\n')); } catch { /* keep scanning */ }
    }
  }
  throw new CliError('hierarchy not JSON:\n' + text.slice(0, 200));
}

// Pure: hierarchy JSON → { refs, tree, count }. Nodes whose bounds fall entirely outside
// the root window get no ref (tapping them would be a silent no-op).
export function assignRefs(json, opts = {}) {
  const refs = {};
  const lines = [];
  let n = 0;
  const browser = !!opts.browser;
  const rootBounds = parseBounds(json?.attributes?.bounds);
  const win = opts.window || (rootBounds && rootBounds.w > 0 && rootBounds.h > 0 ? rootBounds : null);
  const onScreen = (b) => !win || (b.x2 > win.x1 && b.x1 < win.x2 && b.y2 > win.y1 && b.y1 < win.y2);

  function walk(node, depth) {
    if (!node) return;
    const a = node.attributes || {};
    const id = (a['resource-id'] || '').trim();
    if (isSystemChrome(id)) return;
    if (browser && isBrowserChrome(id)) return;
    const text = (a.text || a.accessibilityText || a.hintText || a.label || '').trim();
    if (isDevChrome(text)) return;
    const bounds = parseBounds(a.bounds);
    const kind = summarizeClass(a.class);
    let show = opts.full ? !!bounds : isInteresting(a);
    if (browser && isBrowserPassthrough(id)) show = false;
    if (show && bounds && bounds.w > 0 && bounds.h > 0 && onScreen(bounds)) {
      n += 1;
      const ref = 'e' + n;
      refs[ref] = {
        id,
        text,
        class: a.class || '',
        clickable: a.clickable === 'true' || a.clickable === true,
        x: bounds.cx, y: bounds.cy,
        bounds: [bounds.x1, bounds.y1, bounds.x2, bounds.y2],
        kind,
      };
      const idPart = id ? ` id=${id}` : '';
      const textPart = text ? ` "${text.replace(/\s+/g, ' ').slice(0, 80)}"` : '';
      const indent = '  '.repeat(Math.min(depth, 6));
      lines.push(`${indent}- [${ref}] ${kind}${textPart}${idPart}`);
    }
    for (const child of node.children || []) walk(child, depth + (show ? 1 : 0));
  }
  walk(json, 0);
  return { refs, tree: lines.join('\n'), count: n };
}

function snapshot(state, opts = {}) {
  const r = maestro(state, ['hierarchy']);
  if (!r.ok) throw new CliError('maestro hierarchy failed:\n' + r.err);
  const json = parseHierarchy(r.out);
  const { refs, tree, count } = assignRefs(json, { full: opts.full, browser: isBrowserApp(state.appId) });
  state.refs = refs;
  state.capturedAt = new Date().toISOString();
  saveState(state);
  return { tree, count };
}

export function getRef(state, ref, now = Date.now(), ttlMs = REF_TTL_MS) {
  if (!state.refs || !state.refs[ref]) throw new CliError(`Unknown ref '${ref}'. Run snapshot first.`, EXIT.REF);
  const age = now - Date.parse(state.capturedAt || '');
  if (!(age <= ttlMs)) {
    const secs = Number.isFinite(age) ? `${Math.round(age / 1000)}s old` : 'of unknown age';
    throw new CliError(`Ref '${ref}' is from a snapshot ${secs} (limit ${ttlMs / 1000}s) — run snapshot again.`, EXIT.REF);
  }
  return state.refs[ref];
}

// ---- actions ----
function tap(state, ref) {
  reqDevice(state);
  const r = getRef(state, ref);
  if (state.platform === 'android') {
    return runOk('adb', ['-s', state.device, 'shell', 'input', 'tap', String(r.x), String(r.y)]);
  }
  // iOS sim — simctl has no `io tap` and Maestro has no one-shot tap; run a tapOn-point flow.
  return runFlow(state, [{ tapOn: { point: `${r.x},${r.y}` } }]);
}
function tapById(state, id) {
  if (!id) throw new CliError('tap-id <testID> required', EXIT.USAGE);
  return runFlow(state, [{ tapOn: { id } }]);
}
function fill(state, ref, text) {
  const tapRes = tap(state, ref);
  if (!tapRes.ok) return tapRes;
  sleep(250);
  return runFlow(state, [{ inputText: text }]);
}
function fillById(state, id, text) {
  if (!id) throw new CliError('fill-id <testID> <text...> required', EXIT.USAGE);
  return runFlow(state, [{ tapOn: { id } }, { inputText: text }]);
}
function clearField(state, ref) {
  const tapRes = tap(state, ref);
  if (!tapRes.ok) return tapRes;
  sleep(250);
  return runFlow(state, [{ eraseText: 200 }]); // erase up to 200 chars from the focused field
}

// Wait until a text substring appears in the visible hierarchy, or timeout (polls every 1s).
function waitText(state, substring, timeoutSec = 10) {
  if (!substring) throw new CliError('wait-text <substring> [timeout-sec] required', EXIT.USAGE);
  const deadline = Date.now() + timeoutSec * 1000;
  const start = Date.now();
  while (Date.now() < deadline) {
    const r = maestro(state, ['hierarchy']);
    if (r.ok && r.out.includes(substring)) {
      return { ok: true, out: `found "${substring}" after ${Date.now() - start}ms` };
    }
    sleep(1000);
  }
  return { ok: false, err: `timeout: "${substring}" not seen in ${timeoutSec}s` };
}

const ANDROID_KEYS = { BACK: 'KEYCODE_BACK', ENTER: 'KEYCODE_ENTER', HOME: 'KEYCODE_HOME', TAB: 'KEYCODE_TAB', ESCAPE: 'KEYCODE_ESCAPE' };
const IOS_KEYS = { ENTER: 'Enter', HOME: 'Home' };
function press(state, key) {
  const K = String(key || '').toUpperCase();
  const k = ANDROID_KEYS[K];
  if (!k) throw new CliError(`Unknown key: ${key}. One of: ${Object.keys(ANDROID_KEYS).join(', ')}`, EXIT.USAGE);
  reqDevice(state);
  if (state.platform === 'android') {
    return runOk('adb', ['-s', state.device, 'shell', 'input', 'keyevent', k]);
  }
  // iOS sim: no hardware keys, but Maestro can synthesize Enter and Home.
  if (IOS_KEYS[K]) return runFlow(state, [{ pressKey: IOS_KEYS[K] }]);
  throw new CliError(`press ${K} not supported on iOS sim (only ENTER, HOME). Use an in-app control via snapshot+click.`, EXIT.USAGE);
}

function launch(state) {
  reqApp(state);
  if (state.platform === 'android') {
    // Resolve the launcher activity and am start it; `monkey` breaks on newer images.
    const res = runOk('adb', ['-s', state.device, 'shell', 'cmd', 'package', 'resolve-activity', '--brief', '-c', 'android.intent.category.LAUNCHER', state.appId]);
    const comp = (res.out || '').trim().split('\n').pop()?.trim();
    if (res.ok && comp && comp.includes('/')) {
      return runOk('adb', ['-s', state.device, 'shell', 'am', 'start', '-n', comp]);
    }
    return runOk('adb', ['-s', state.device, 'shell', 'monkey', '-p', state.appId, '-c', 'android.intent.category.LAUNCHER', '1']);
  }
  return runOk('xcrun', ['simctl', 'launch', state.device, state.appId]);
}
function stop(state) {
  reqApp(state);
  if (state.platform === 'android') return runOk('adb', ['-s', state.device, 'shell', 'am', 'force-stop', state.appId]);
  return runOk('xcrun', ['simctl', 'terminate', state.device, state.appId]);
}
function relaunchClean(state) {
  reqApp(state);
  if (state.platform !== 'android') throw new CliError('relaunch-clean is android-only (use stop+launch on ios).', EXIT.USAGE);
  stop(state);
  runOk('adb', ['-s', state.device, 'shell', 'pm', 'clear', state.appId]);
  return launch(state);
}

function screenshot(state, path) {
  reqDevice(state);
  if (!path) throw new CliError('screenshot <path> required', EXIT.USAGE);
  mkdirSync(dirname(path) || '.', { recursive: true });
  if (state.platform === 'android') {
    try {
      const png = execFileSync('adb', ['-s', state.device, 'exec-out', 'screencap', '-p'], {
        stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 64 * 1024 * 1024,
      });
      writeFileSync(path, png);
      return { ok: true, out: `saved ${path}` };
    } catch (e) {
      return { ok: false, err: e.stderr?.toString() || e.message };
    }
  }
  const r = runOk('xcrun', ['simctl', 'io', state.device, 'screenshot', path]);
  return r.ok ? { ok: true, out: `saved ${path}` } : r;
}

function deepLink(state, url) {
  reqApp(state);
  if (!url) throw new CliError('deep-link|open-url <url> required', EXIT.USAGE);
  if (state.platform === 'android') {
    return runOk('adb', ['-s', state.device, 'shell', 'am', 'start', '-W', '-a', 'android.intent.action.VIEW', '-d', url, state.appId]);
  }
  return runOk('xcrun', ['simctl', 'openurl', state.device, url]);
}

function running(state) {
  reqDevice(state);
  if (state.platform === 'android') {
    const r = runOk('adb', ['-s', state.device, 'shell', 'dumpsys', 'window']);
    if (!r.ok) return r;
    return { ok: true, out: r.out.split('\n').filter((l) => /mCurrentFocus|mFocusedApp/.test(l)).join('\n') };
  }
  const r = runOk('xcrun', ['simctl', 'listapps', state.device]);
  return r.ok ? { ok: true, out: r.out.slice(0, 400) } : r;
}

export function parseSince(args) {
  const i = args.indexOf('--since');
  if (i < 0) return 60;
  const v = args[i + 1];
  if (!/^\d+$/.test(v || '') || Number(v) <= 0) {
    throw new CliError('--since needs a positive integer number of seconds', EXIT.USAGE);
  }
  return Number(v);
}
function logs(state, args) {
  reqDevice(state);
  const errors = args.includes('--errors');
  const since = parseSince(args);
  if (state.platform === 'android') {
    const t = new Date(Date.now() - since * 1000);
    const p2 = (x) => String(x).padStart(2, '0');
    const ts = `${p2(t.getMonth() + 1)}-${p2(t.getDate())} ${p2(t.getHours())}:${p2(t.getMinutes())}:${p2(t.getSeconds())}.000`;
    const r = runOk('adb', ['-s', state.device, 'logcat', '-d', '-T', ts, errors ? '*:E' : '*:W']);
    return r.ok ? { ok: true, out: (r.out || '').split('\n').slice(-400).join('\n') } : r;
  }
  const r = runOk('xcrun', ['simctl', 'spawn', state.device, 'log', 'show', '--last', `${since}s`, '--predicate', `processImagePath contains "${state.appId || ''}"`]);
  return r.ok ? { ok: true, out: (r.out || '').split('\n').slice(-400).join('\n') } : r;
}
function logsClear(state) {
  reqDevice(state);
  if (state.platform === 'android') return runOk('adb', ['-s', state.device, 'logcat', '-c']);
  return { ok: true, out: '(ios log buffer not clearable)' };
}

// ---- recording ----
function readRec() {
  if (!existsSync(recPath())) return null;
  try { return JSON.parse(readFileSync(recPath(), 'utf8')); } catch { return null; }
}
function recordStart(state, outPath) {
  reqDevice(state);
  if (!outPath) throw new CliError('record-start <path.mp4> required', EXIT.USAGE);
  if (readRec()) throw new CliError('Recording already in progress (run record-stop first).');
  mkdirSync(dirname(outPath) || '.', { recursive: true });
  const startedAt = new Date().toISOString();
  if (state.platform === 'android') {
    // Record ON the device into a real mp4 container, pull it at record-stop.
    const devicePath = `/sdcard/_mcli_rec_${process.pid}.mp4`;
    const r = runOk('adb', ['-s', state.device, 'shell',
      `screenrecord --time-limit 180 ${devicePath} </dev/null >/dev/null 2>&1 & echo $!`]);
    const devicePid = parseInt((r.out || '').trim().split('\n').pop(), 10);
    if (!r.ok || !Number.isInteger(devicePid)) throw new CliError('could not start screenrecord: ' + (r.err || r.out));
    writeFileSync(recPath(), JSON.stringify({ platform: 'android', device: state.device, devicePid, devicePath, outPath, startedAt }));
    return { ok: true, out: `recording on device (pid ${devicePid}) → ${outPath} (max 180s)` };
  }
  const proc = spawn('xcrun', ['simctl', 'io', state.device, 'recordVideo', outPath], { stdio: 'ignore', detached: true });
  proc.unref();
  writeFileSync(recPath(), JSON.stringify({ platform: 'ios', device: state.device, pid: proc.pid, outPath, startedAt }));
  return { ok: true, out: `recording pid=${proc.pid} → ${outPath}` };
}
function recordStop() {
  const rec = readRec();
  if (!rec) throw new CliError('No recording in progress.');
  if (rec.platform === 'android') {
    if (!Number.isInteger(rec.devicePid) || !rec.devicePath || !rec.outPath || !rec.device) {
      throw new CliError(`corrupt recording record — delete ${recPath()} and retry`);
    }
    runOk('adb', ['-s', rec.device, 'shell', 'kill', '-2', String(rec.devicePid)]);
    sleep(1500);
    for (let i = 0; i < 10; i++) { // wait for screenrecord to finalise the file
      const alive = runOk('adb', ['-s', rec.device, 'shell', 'kill', '-0', String(rec.devicePid)]);
      if (!alive.ok) break;
      sleep(500);
    }
    const pull = runOk('adb', ['-s', rec.device, 'pull', rec.devicePath, rec.outPath]);
    runOk('adb', ['-s', rec.device, 'shell', 'rm', '-f', rec.devicePath]);
    unlinkSync(recPath());
    return pull.ok ? { ok: true, out: `saved ${rec.outPath}` } : { ok: false, err: pull.err || pull.out };
  }
  if (!Number.isInteger(rec.pid)) throw new CliError(`corrupt recording record — delete ${recPath()} and retry`);
  let alive = true;
  try { process.kill(rec.pid, 0); } catch { alive = false; }
  if (alive) { try { process.kill(rec.pid, 'SIGINT'); } catch { /* already gone */ } }
  unlinkSync(recPath());
  return alive
    ? { ok: true, out: `stopped pid=${rec.pid} → ${rec.outPath}` }
    : { ok: false, err: `recorder pid=${rec.pid} was not running — ${rec.outPath} may be incomplete` };
}

// ---- boot ----
function listAvds() {
  const r = runOk('emulator', ['-list-avds']);
  return r.ok ? r.out.split('\n').map((s) => s.trim()).filter((s) => /^[\w.-]+$/.test(s)) : [];
}
function boot(name) {
  if (!name) throw new CliError('boot <avd|sim-name|udid> required', EXIT.USAGE);
  const sim = detectPlatform(name, { simDevices: listSimDevices() });
  if (sim) {
    const b = runOk('xcrun', ['simctl', 'boot', sim.device]);
    if (!b.ok && !/already booted|current state: Booted/i.test(b.err || '')) throw new CliError('simctl boot failed: ' + b.err);
    runOk('open', ['-a', 'Simulator']);
    runOk('xcrun', ['simctl', 'bootstatus', sim.device, '-b']);
    return sim;
  }
  const avds = listAvds();
  if (!avds.includes(name)) {
    throw new CliError(`'${name}' is neither an iOS simulator nor an Android AVD (emulator -list-avds: ${avds.join(', ') || 'none'})`, EXIT.USAGE);
  }
  // Adopt an emulator that is already running this AVD instead of spawning a
  // second one (which would wait 180 s for a serial that never boots).
  for (const s of listAdbSerials().filter((x) => x.startsWith('emulator-'))) {
    const r = runOk('adb', ['-s', s, 'emu', 'avd', 'name']);
    const running = (r.out || '').split('\n')[0].trim();
    if (running !== name) continue;
    const done = runOk('adb', ['-s', s, 'shell', 'getprop', 'sys.boot_completed']);
    if ((done.out || '').trim() === '1') return { platform: 'android', device: s, deviceName: name };
  }
  const before = listAdbSerials();
  const proc = spawn('emulator', ['-avd', name, '-no-snapshot', '-no-boot-anim'], { stdio: 'ignore', detached: true });
  proc.unref();
  const deadline = Date.now() + 180_000;
  let serial = null;
  while (Date.now() < deadline) {
    const fresh = listAdbSerials().filter((s) => s.startsWith('emulator-') && !before.includes(s));
    if (fresh.length) {
      const done = runOk('adb', ['-s', fresh[0], 'shell', 'getprop', 'sys.boot_completed']);
      if ((done.out || '').trim() === '1') { serial = fresh[0]; break; }
    }
    sleep(2000);
  }
  if (!serial) throw new CliError('emulator did not finish booting within 180s');
  return { platform: 'android', device: serial, deviceName: name };
}

// Adopt a resolved device: per-device state file (unless --state/$MOBILE_CLI_STATE), refs cleared.
function adoptDevice(state, res) {
  if (!STATE_PATH_EXPLICIT) {
    STATE_PATH = join(MCLI_DIR, `${sanitizeDeviceId(res.device)}.json`);
    mkdirSync(MCLI_DIR, { recursive: true });
    writeFileSync(CURRENT_POINTER, STATE_PATH);
    const existing = loadStateFrom(STATE_PATH);
    for (const k of Object.keys(state)) delete state[k];
    Object.assign(state, existing);
  }
  state.device = res.device;
  state.deviceName = res.deviceName || null;
  state.platform = res.platform;
  state.refs = {};
  state.capturedAt = null;
  saveState(state);
}

export function readVersion(here = HERE) {
  const vf = join(here, 'VERSION'); // written by `qualiow init` next to the copied driver
  if (existsSync(vf)) {
    const v = readFileSync(vf, 'utf8').trim();
    if (v) return v;
  }
  const pj = join(here, '..', 'package.json');
  if (existsSync(pj)) {
    try {
      const p = JSON.parse(readFileSync(pj, 'utf8'));
      if (p.name === 'qualiow-exploratory-testing' && p.version) return p.version;
    } catch { /* ignore */ }
  }
  return 'unknown';
}

